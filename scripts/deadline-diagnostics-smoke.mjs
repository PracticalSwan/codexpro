import assert from 'node:assert/strict';
import { TelemetryRegistry } from '../dist/telemetry.js';
import { loadConfig } from '../dist/config.js';
import { toolSurfaceDiagnostics } from '../dist/diagnosticsOps.js';
import { toolNamesForMode } from '../dist/server.js';

const telemetry = new TelemetryRegistry({ maxEvents: 16, maxCounters: 64 });
const secret = 'sk-plan28-secret-abcdefghijklmnopqrstuvwxyz';
telemetry.record({ stage: 'resilience', status: 'degraded', event: 'deadline_yield', tool: 'verify_changes', reason: `TOKEN=${secret}`, entityId: 'job_123', stdout: secret, command: secret });
telemetry.record({ stage: 'resilience', status: 'ok', event: 'async_routed', tool: 'verify_changes', reason: 'high variance verification' });
telemetry.record({ stage: 'resilience', status: 'degraded', event: 'deadline_limited_child', tool: 'run_checks', entityId: 'check_123', reason: 'deadline limited child' });
telemetry.record({ stage: 'resilience', status: 'ok', event: 'job_started', tool: 'start_verification', entityId: 'job_123', reason: 'started' });
telemetry.record({ stage: 'resilience', status: 'ok', event: 'job_completed', tool: 'job_status', entityId: 'job_123', reason: 'completed' });
telemetry.record({ stage: 'resilience', status: 'degraded', event: 'job_interrupted', tool: 'job_status', entityId: 'job_456', reason: 'interrupted' });
telemetry.record({ stage: 'resilience', status: 'ok', event: 'batch_continued', tool: 'gather_context', entityId: 'batch_123', reason: 'continued' });
const snapshot = telemetry.snapshot();
const serialized = JSON.stringify(snapshot);
assert(!serialized.includes(secret));
assert(!serialized.includes('stdout'));
assert(!serialized.includes('command'));
assert.equal(snapshot.counters['event:deadline_yield'], 1);
assert.equal(snapshot.counters['event:async_routed'], 1);
for (const event of ['deadline_limited_child','job_started','job_completed','job_interrupted','batch_continued']) assert.equal(snapshot.counters[`event:${event}`], 1, `missing ${event} counter`);
assert(snapshot.events[0].reason.length <= 240);
const config = loadConfig(['--root', process.cwd(), '--allow-root', process.cwd(), '--tool-mode', 'full', '--bash', 'safe']);
assert(toolNamesForMode(config).includes('tool_time_probe'), 'tool_time_probe missing from configured tool surface');
const tools = ['start_workspace_process','job_status','start_checks','start_verification','gather_context','inspect_workspace','propose_goal','run_checks','verify_changes'];
const diagnostics = toolSurfaceDiagnostics(config, tools, tools, snapshot);
assert.equal(diagnostics.deadline.sync_call_deadline_mode, 'bounded');
assert.equal(diagnostics.deadline.sync_call_deadline_ms, 1_200_000);
assert.equal(diagnostics.deadline.sync_call_deadline_minutes, 20);
assert.equal(diagnostics.deadline.sync_call_deadline_default_ms, 1_200_000);
assert.equal(diagnostics.deadline.sync_call_deadline_min_ms, 300_000);
assert.equal(diagnostics.deadline.sync_call_deadline_max_ms, 3_600_000);
assert.equal(diagnostics.capabilities.managed_processes, 'available');
assert.equal(diagnostics.capabilities.structured_jobs, 'available');
assert.equal(diagnostics.capabilities.resumable_batches, 'available');
assert.equal(diagnostics.capabilities.durable_goals, 'available');
assert.equal(diagnostics.resilience.deadline_yields, 1);
assert.equal(diagnostics.resilience.async_routes, 1);
assert.equal(diagnostics.resilience.deadline_limited_children, 1);
assert.equal(diagnostics.resilience.job_started, 1);
assert.equal(diagnostics.resilience.job_completed, 1);
assert.equal(diagnostics.resilience.job_interrupted, 1);
assert.equal(diagnostics.resilience.batch_continued, 1);
assert(diagnostics.timeout_risks.some((risk) => risk.tool === 'verify_changes' && risk.recommended_primitive === 'start_verification'));
console.log('deadline diagnostics smoke passed');
